/**
 * Работа с ИНН в формах справочников (подрядчики, поставщики).
 * Требование сервера: ровно 10 или 12 цифр (server/src/schemas/common.ts).
 */

/** Текст ошибки формата — совпадает с сообщением серверной валидации */
export const INN_FORMAT_MESSAGE = 'ИНН должен содержать 10 или 12 цифр'

/**
 * Нормализация: вырезаем пробелы (в т.ч. неразрывные и табуляцию) — реквизиты часто
 * копируют из письма или PDF вместе с ними. Остальные символы не трогаем: строка вида
 * «ИНН 7730556178» останется невалидной и будет отклонена с понятным сообщением.
 */
export const normalizeInn = (value: string): string => value.replace(/\s/g, '')

/** Проверка формата ИНН после нормализации */
export const isValidInn = (value: string): boolean => /^\d{10}$|^\d{12}$/.test(normalizeInn(value))
