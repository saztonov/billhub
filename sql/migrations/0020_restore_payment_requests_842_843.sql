-- Миграция 0020: разовое восстановление ошибочно удалённых заявок 842 и 843.
--
-- Контекст:
--   22.07.2026 заявки 842 и 843 (ООО «АЛЬЯНС», ЖК Зиларт лот 33, обе в статусе «Отклонена»)
--   были удалены по ошибке. Удаление мягкое (is_deleted/deleted_at), строки и все связанные
--   данные — файлы, комментарии, решения Штаба, stage_history — сохранились полностью.
--   Флаг is_deleted жёстко фильтрует все выборки (список заявок, очереди согласования,
--   вкладки «Согласовано»/«Отклонено»), поэтому заявок не видит никто из участников процесса.
--   Снятие флага возвращает видимость всем ролям; статус, этапы и решения не меняем —
--   заявки остаются в текущем отклонённом статусе.
--
-- Прочие ранее удалённые заявки НЕ трогаем — они удалялись осознанно.
--
-- Без top-level BEGIN/COMMIT — runner оборачивает миграцию в транзакцию (ADR-0002).
-- Идемпотентность — через условие is_deleted = true: повторный накат ничего не изменит
-- и не продублирует запись в истории.

UPDATE public.payment_requests
SET is_deleted = false,
    deleted_at = NULL,
    stage_history = COALESCE(stage_history, '[]'::jsonb) || jsonb_build_object(
      'event', 'restore',
      'note', 'снят флаг удаления (ошибочное удаление 22.07.2026, миграция 0020)',
      'at', to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
WHERE request_number IN ('842', '843')
  AND is_deleted = true;
